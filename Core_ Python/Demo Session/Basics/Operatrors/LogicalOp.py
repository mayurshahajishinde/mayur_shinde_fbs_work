#logical operator= working and perform on multiple conditions

#1.and= if two conditions are true then return true otherwise return false

print(True and True)  #o/p true
print(True and False)  #o/p false

#2.or= if both conditions are false then return false otherwise return true

print(False or False)   #o/p false
print(False or True)    #o/p true

#3.not= perform on only one condition 
    #=it gives opposite output of condition
    #= this is known as single operand
print(not False)  #o/p true
print(not True)   #o/p false
  
